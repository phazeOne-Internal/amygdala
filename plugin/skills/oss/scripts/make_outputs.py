#!/usr/bin/env python3
"""Generate THIRD_PARTY_NOTICES.md and a CycloneDX 1.5 SBOM from the reviewer-confirmed component list.

Usage:
  python make_outputs.py <repo-root> --confirmed <out>/confirmed_components.json --out-dir <out>

confirmed_components.json (written by the reviewer after checking components.json):
{
  "product": {"name": "Smart Thermostat", "version": "1.4.2", "supplier": "Acme Ltd"},
  "components": [
    {"name": "FreeRTOS-Kernel", "version": "10.6.2", "path": "mtb_shared/freertos/release-v10.6.202",
     "license": "MIT", "shipped_in": ["mcu-firmware"], "distribution": "linked",
     "supplier": "Amazon / FreeRTOS", "purl": "pkg:github/FreeRTOS/FreeRTOS-Kernel@V10.6.2",
     "license_file": "mtb_shared/freertos/release-v10.6.202/LICENSE.md", "modified": false, "notes": ""}
  ]
}
distribution: linked | dynamic | separate-program | firmware-blob | build-tool | test-only | not-distributed
Only components that ship (distribution not in build-tool/test-only/not-distributed) go into the notices;
all components go into the SBOM, with distribution as a property.

Nothing is invented: when a licence text can't be found, the notice says so and the script lists it as a gap.
"""
import argparse
import datetime
import json
import os
import sys
import uuid

if sys.version_info < (3, 8):
    sys.exit("This script needs Python 3.8 or later (any interpreter on PATH is fine); found " + sys.version.split()[0])

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

NOT_SHIPPED = {"build-tool", "test-only", "not-distributed"}


def read(root, rel):
    if not rel:
        return None
    p = os.path.join(root, rel)
    try:
        with open(p, encoding="utf-8", errors="replace") as fh:
            return fh.read()
    except OSError:
        return None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("root")
    ap.add_argument("--confirmed", required=True)
    ap.add_argument("--out-dir", required=True)
    args = ap.parse_args()
    root = os.path.abspath(args.root)
    with open(args.confirmed, encoding="utf-8") as fh:
        conf = json.load(fh)
    prod = conf.get("product", {})
    comps = conf.get("components", [])
    errs = [f"components[{i}] missing name/license" for i, c in enumerate(comps) if not c.get("name") or not c.get("license")]
    if errs:
        sys.exit("confirmed_components.json problems:\n  " + "\n  ".join(errs))
    os.makedirs(args.out_dir, exist_ok=True)

    # ScanCode copyright statements (if a scan was run into the same out-dir) feed the notices.
    copyrights = {}
    sc_path = os.path.join(args.out_dir, "scancode.json")
    if os.path.isfile(sc_path):
        try:
            sc = json.load(open(sc_path, encoding="utf-8"))
            for f in sc.get("files", []):
                for h in f.get("copyrights", []):
                    copyrights.setdefault(f["path"].replace("\\", "/"), []).append(h.get("copyright", "").strip())
        except (OSError, ValueError):
            pass

    def holders(c):
        base = (c.get("path") or "").rstrip("/")
        found = []
        for path, lines in copyrights.items():
            if base and (path == base or path.startswith(base + "/")):
                for l in lines:
                    if l and l not in found:
                        found.append(l)
        return found[:15]

    # ---- notices
    gaps = []
    shipped = [c for c in comps if c.get("distribution") not in NOT_SHIPPED]
    L = [f"# Third-party software notices — {prod.get('name', 'Product')} {prod.get('version', '')}".rstrip(), "",
         "This product includes the third-party software listed below. Each component is provided under the licence shown; "
         "the full licence texts follow.", "",
         "> DRAFT generated by the ./phazeOne amygdala:oss skill. Have it checked by whoever owns open-source compliance before it ships.", "",
         "| Component | Version | Licence | Used in |", "|---|---|---|---|"]
    for c in sorted(shipped, key=lambda c: c["name"].lower()):
        L.append(f"| {c['name']} | {c.get('version') or ''} | {c['license']} | {', '.join(c.get('shipped_in', []))} |")
    L.append("")
    for c in sorted(shipped, key=lambda c: c["name"].lower()):
        L += [f"## {c['name']} {c.get('version') or ''}".rstrip(), "", f"Licence: {c['license']}"]
        if c.get("supplier"):
            L.append(f"Supplier: {c['supplier']}")
        for line in holders(c):
            L.append(f"{line}  ")
        if c.get("modified"):
            L.append("This component has been modified by the product manufacturer.")
        txt = read(root, c.get("license_file"))
        if txt:
            L += ["", "```text", txt.strip(), "```", ""]
        else:
            L += ["", f"**Licence text not found in the repository** (expected at `{c.get('license_file') or '?'}`). "
                  "Obtain the exact text from the component's source distribution before release.", ""]
            gaps.append(c["name"])
        notice = read(root, os.path.join(os.path.dirname(c["license_file"]), "NOTICE")) if c.get("license_file") else None
        if notice:
            L += ["NOTICE:", "", "```text", notice.strip(), "```", ""]
    with open(os.path.join(args.out_dir, "THIRD_PARTY_NOTICES.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(L) + "\n")

    # ---- CycloneDX 1.5
    def lic(c):
        expr = c["license"]
        if any(tok in expr for tok in (" AND ", " OR ", " WITH ")):
            return [{"expression": expr}]
        if expr.startswith("LicenseRef-") or " " in expr:
            return [{"license": {"name": expr}}]
        return [{"license": {"id": expr}}]

    bom_comps = []
    for c in comps:
        entry = {"type": "firmware" if c.get("distribution") == "firmware-blob" else "library",
                 "bom-ref": c.get("purl") or f"{c['name']}@{c.get('version') or 'unknown'}",
                 "name": c["name"], "licenses": lic(c),
                 "properties": [{"name": "distribution", "value": c.get("distribution", "unknown")},
                                {"name": "shipped_in", "value": ",".join(c.get("shipped_in", []))},
                                {"name": "modified", "value": str(bool(c.get("modified"))).lower()},
                                {"name": "path", "value": c.get("path", "")}]}
        if c.get("version"):
            entry["version"] = c["version"]
        if c.get("purl"):
            entry["purl"] = c["purl"]
        if c.get("supplier"):
            entry["supplier"] = {"name": c["supplier"]}
        bom_comps.append(entry)
    bom = {"bomFormat": "CycloneDX", "specVersion": "1.5", "serialNumber": f"urn:uuid:{uuid.uuid4()}", "version": 1,
           "metadata": {"timestamp": datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat(),
                        "tools": {"components": [{"type": "application", "name": "phazeOne amygdala:oss skill"}]},
                        "component": {"type": "device", "name": prod.get("name", "product"), "version": prod.get("version", ""),
                                      **({"supplier": {"name": prod["supplier"]}} if prod.get("supplier") else {})}},
           "components": bom_comps}
    with open(os.path.join(args.out_dir, "sbom.cdx.json"), "w", encoding="utf-8") as fh:
        json.dump(bom, fh, indent=2, ensure_ascii=False)
    print(f"notices: {len(shipped)} shipped components ({len(gaps)} missing licence text) -> THIRD_PARTY_NOTICES.md")
    print(f"sbom: {len(bom_comps)} components -> sbom.cdx.json (CycloneDX 1.5)")
    if gaps:
        print("missing licence text: " + ", ".join(gaps))


if __name__ == "__main__":
    main()
